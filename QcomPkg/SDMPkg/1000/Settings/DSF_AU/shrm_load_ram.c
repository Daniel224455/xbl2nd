void SHRM_Clear_SHRM_STRUCT_Periodic_training_DRAM_Region (void)
{
 
// Clear SHRM_STRUCT and Periodic training data struct  Address region 
    uint32 *shrm_local_ptr = (uint32 *)(SEQ_DDR_SS_SHRM_MEM_SHRM_OFFSET + 0x0B38); 
    uint32 i = 0; 
    uint32 no_of_bytes = 0; 
 
    no_of_bytes =  RODATA_SECTION_OFFSET_FULL - 0xB38;
 
    for(i=0; i< (no_of_bytes/4);i++) 
        *shrm_local_ptr++ =0x0; 
 
    shrm_local_ptr = 0; 
}
 
